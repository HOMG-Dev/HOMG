public class Introduction
{
    public string usedMilitaryFactory;
    public string totalMilitaryFactory;
    public string usedCivilFactory;
    public string totalCivilFactory;
    public string usedUnit;
    public string totalUnit;

    public Introduction(string usedMilitaryFactory, string totalMilitaryFactory, string usedCivilFactory, string totalCivilFactory, string usedUnit, string totalUnit)
    {
        this.usedMilitaryFactory = usedMilitaryFactory;
        this.totalMilitaryFactory = totalMilitaryFactory;
        this.usedCivilFactory = usedCivilFactory;
        this.totalCivilFactory = totalCivilFactory;
        this.usedUnit = usedUnit;
        this.totalUnit = totalUnit;
    }
}

